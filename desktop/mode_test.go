func TestGetEnv(t *testing.T) {
	t.Setenv("HELIOS_ATS_TEST_VAR", "set-value")
	if got := getEnv("HELIOS_ATS_TEST_VAR", "default"); got != "set-value" {
		t.Errorf("getEnv = %q, want %q", got, "set-value")
	}

	os.Unsetenv("HELIOS_ATS_TEST_VAR")
	if got := getEnv("HELIOS_ATS_TEST_VAR", "default"); got != "default" {
		t.Errorf("getEnv = %q, want %q", got, "default")
	}
}

// TestParseUserDirsDownload exercises parseUserDirsDownload directly:
// exact line syntax, $HOME expansion, and the various ways a file fails to
// yield anything. Ported verbatim from the sibling ingestion service's own
// mode_test.go.
func TestParseUserDirsDownload(t *testing.T) {
	tests := []struct {
		name    string
		content string
		wantOK  bool
		wantDir string // relative to home when wantOK
	}{
		{
			name:    "simple $HOME-relative entry",
			content: `XDG_DOWNLOAD_DIR="$HOME/Downloads"` + "\n",
			wantOK:  true,
			wantDir: "Downloads",
		},
		{
			name: "surrounded by other XDG_*_DIR lines and a comment",
			content: "# generated by xdg-user-dirs-update\n" +
				`XDG_DESKTOP_DIR="$HOME/Desktop"` + "\n" +
				`XDG_DOWNLOAD_DIR="$HOME/MyDownloads"` + "\n",
			wantOK:  true,
			wantDir: "MyDownloads",
		},
		{
			name:    "leading whitespace tolerated",
			content: `  XDG_DOWNLOAD_DIR="$HOME/Downloads"` + "\n",
			wantOK:  true,
			wantDir: "Downloads",
		},
		{
			name:    "unquoted value is not the real xdg-user-dirs-update format, rejected",
			content: "XDG_DOWNLOAD_DIR=$HOME/Downloads\n",
			wantOK:  false,
		},
		{
			name:    "no XDG_DOWNLOAD_DIR line at all",
			content: `XDG_DESKTOP_DIR="$HOME/Desktop"` + "\n",
			wantOK:  false,
		},
		{
			name:    "relative value even after $HOME expansion is rejected",
			content: `XDG_DOWNLOAD_DIR="not/absolute"` + "\n",
			wantOK:  false,
		},
		{
			name:    "empty file",
			content: "",
			wantOK:  false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			home := t.TempDir()
			path := filepath.Join(t.TempDir(), "user-dirs.dirs")
			if err := os.WriteFile(path, []byte(tt.content), 0o644); err != nil {
				t.Fatalf("setup: %v", err)
			}

			got, ok := parseUserDirsDownload(path, home)
			if ok != tt.wantOK {
				t.Fatalf("parseUserDirsDownload ok = %v, want %v (dir = %q)", ok, tt.wantOK, got)
			}
			if !tt.wantOK {
				return
			}
			if want := filepath.Join(home, tt.wantDir); got != want {
				t.Errorf("parseUserDirsDownload dir = %q, want %q", got, want)
			}
		})
	}

	t.Run("missing file", func(t *testing.T) {
		home := t.TempDir()
		got, ok := parseUserDirsDownload(filepath.Join(t.TempDir(), "does-not-exist"), home)
		if ok {
			t.Fatalf("parseUserDirsDownload ok = true for a missing file, dir = %q", got)
		}
	})
}

// TestSystemDownloadDir_PrefersXDGDownloadDirEnv proves an absolute
// $XDG_DOWNLOAD_DIR wins outright, per systemDownloadDir's documented
// order, without even looking at user-dirs.dirs or ~/Downloads.
func TestSystemDownloadDir_PrefersXDGDownloadDirEnv(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("XDG_DOWNLOAD_DIR", dir)

	got, err := systemDownloadDir()
	if err != nil {
		t.Fatalf("systemDownloadDir: %v", err)
	}
	if got != dir {
		t.Errorf("systemDownloadDir = %q, want %q", got, dir)
	}
}

// TestSystemDownloadDir_FallsBackToHomeDownloads proves the plain
// ~/Downloads fallback when neither $XDG_DOWNLOAD_DIR nor
// user-dirs.dirs yields anything.
func TestSystemDownloadDir_FallsBackToHomeDownloads(t *testing.T) {
	os.Unsetenv(xdgDownloadDirEnv)
	home := t.TempDir()
	t.Setenv("HOME", home)
	downloads := filepath.Join(home, downloadsSubdir)
	if err := os.MkdirAll(downloads, 0o755); err != nil {
		t.Fatalf("setup: %v", err)
	}

	got, err := systemDownloadDir()
	if err != nil {
		t.Fatalf("systemDownloadDir: %v", err)
	}
	if got != downloads {
		t.Errorf("systemDownloadDir = %q, want %q", got, downloads)
	}
}
